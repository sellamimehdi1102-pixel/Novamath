_U = (4, 2)  # vecteur de la translation qui transforme M en N


def _t(p, u=_U):
    return (p[0] + u[0], p[1] + u[1])


# ── Figure 1 : image d'un point, parallélogramme ────────────────────────────
_M, _N = (0, 4), (4, 6)
_A = (1, 1)
_A2 = _t(_A)
assert (_N[0] - _M[0], _N[1] - _M[1]) == _U
assert_parallel(_M, _N, _A, _A2)
assert abs(dist(_M, _A) - dist(_N, _A2)) < 1e-12
