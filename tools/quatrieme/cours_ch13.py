_K, _ANG = 0.5, math.radians(45)


def cav(x, y, z):
    """Projection en perspective cavalière : x vers la droite, y en profondeur, z vers le haut."""
    return (round(x + _K * y * math.cos(_ANG), 3), round(z + _K * y * math.sin(_ANG), 3))


def _cache(a, b, **kw):
    s = seg(a, b, **kw)
    s["dashed"] = True
    return s


