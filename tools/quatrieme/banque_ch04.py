def ok(cond):
    return lambda: None if cond else "valeur incohérente"


def divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def common_divisors(a, b):
    return [d for d in divisors(gcd(a, b))]


def dec(n):
    return " \\times ".join(str(p) for p in prime_factors(n))


