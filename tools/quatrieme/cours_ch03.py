def _rect(x0, y0, x1, y1, tooltip, reveal=None, variant=None):
    return poly([{"x": x0, "y": y0}, {"x": x1, "y": y0}, {"x": x1, "y": y1}, {"x": x0, "y": y1}],
                tooltip, reveal=reveal, variant=variant)


