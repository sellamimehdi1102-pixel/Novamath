def ok(cond):
    return lambda: None if cond else "valeur incohérente"


def sci(x):
    """(mantisse, exposant) de l'écriture scientifique d'un décimal positif."""
    x = Dc(str(x))
    e = x.adjusted()
    return (x.scaleb(-e).normalize(), e)


