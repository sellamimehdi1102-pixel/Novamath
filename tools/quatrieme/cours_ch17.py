# ── Figure 4 : une cible carrée ─────────────────────────────────────────────
def _carre(c, tooltip, variant, reveal=None):
    h = c / 2
    return poly([P(-h, -h), P(h, -h), P(h, h), P(-h, h)], tooltip, reveal=reveal, variant=variant)


