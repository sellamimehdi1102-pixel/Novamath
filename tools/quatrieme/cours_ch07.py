def _rect(x, y, w, h, tooltip, reveal=None, variant=None):
    return poly([{"x": x, "y": y}, {"x": x + w, "y": y}, {"x": x + w, "y": y + h}, {"x": x, "y": y + h}],
                tooltip, reveal=reveal, variant=variant)


# ── Figure 1 : la balance 3x + 2 = 11 ───────────────────────────────────────
_U = 0.7  # côté d'une masse de 1


def _plateau(x0, nx, nu, retire=0, reveal_retire=None):
    out, x = [], x0
    for _ in range(nx):
        out.append(_rect(x, 1.0, _U, 1.6, "une boîte de masse x", variant="a"))
        x += _U + 0.1
    for i in range(nu):
        rev = reveal_retire if i >= nu - retire else None
        out.append(_rect(x, 1.0, _U, _U, "une masse de 1" + (" (retirée à l'étape 2)" if rev else ""),
                         variant="b", reveal=None))
        x += _U + 0.1
    return out


