# Triangle ABC rectangle en C : AC = 4, BC = 3, AB = 5 ; angle en A ≈ 36,87°.
_A, _C, _B = (0.0, 0.0), (4.0, 0.0), (4.0, 3.0)
assert abs(dist(_A, _B) - 5) < 1e-9
_ANGLE_A = direction_deg(_A, _B)
assert abs(math.cos(math.radians(_ANGLE_A)) - 0.8) < 1e-12


def _tri(A, B, C, **extra):
    return [pt(*A, "A"), pt(*B, "B"), pt(*C, "C")]


