_VALEURS = (Fr(-3), Fr(-1), Fr(0), Fr(1), Fr(2), Fr(5), Fr(7, 2))


def ok(cond):
    return lambda: None if cond else "valeur incohérente"


def same(f, g):
    """Deux expressions d'une variable sont égales pour plusieurs valeurs (dont des non entières)."""
    return ok(all(f(x) == g(x) for x in _VALEURS))


