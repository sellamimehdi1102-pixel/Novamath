def _rect(x, y, w, h, tooltip, reveal=None, variant=None):
    return poly([{"x": x, "y": y}, {"x": x + w, "y": y}, {"x": x + w, "y": y + h}, {"x": x, "y": y + h}],
                tooltip, reveal=reveal, variant=variant)


