# ── Figure 2 : réduire avec des tuiles (x = bande, 1 = carré) ───────────────
_X, _H = 2.4, 1.0


def _tuiles(x0, y0, nx, nu, reveal=None, variant=None):
    out, x = [], x0
    for _ in range(nx):
        out.append(_rect(x, y0, _X, _H, "une tuile x", reveal=reveal, variant=variant or "a"))
        x += _X + 0.15
    for _ in range(nu):
        out.append(_rect(x, y0, _H, _H, "une tuile 1", reveal=reveal, variant=variant or "b"))
        x += _H + 0.15
    return out


_ligne1 = _tuiles(0.0, 4.0, 2, 3)
