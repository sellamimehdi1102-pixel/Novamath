def ok(cond):
    return lambda: None if cond else "valeur incohérente"


def med(values):
    v = sorted(values)
    n = len(v)
    return Fr(v[n // 2]) if n % 2 else Fr(v[n // 2 - 1] + v[n // 2], 2)


def serie(table):
    return [x for x, e in table for _ in range(e)]


def moy(values):
    return Fr(sum(values), len(values))


