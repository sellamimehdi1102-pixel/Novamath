def _zero(expr):
    return sp.simplify(sp.sympify(expr)) == 0


def _sol(eq, var, attendu):
    return set(sp.solveset(eq, var, domain=sp.S.Reals)) == set(attendu)


def _ensemble(expr, attendu):
    """Deux équations cartésiennes équivalentes (expr = 0 et attendu = 0) à un facteur non nul près."""
    q = sp.simplify(sp.expand(expr) / sp.expand(attendu))
    return q.free_symbols == set() and q != 0


