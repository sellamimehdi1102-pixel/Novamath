def _s(a, b, **kw):
    s = {"from": {"x": a[0], "y": a[1]}, "to": {"x": b[0], "y": b[1]}}
    s.update({k: v for k, v in kw.items() if v is not None})
    return s


def _rect(x0, y0, x1, y1, **kw):
    return [_s((x0, y0), (x1, y0), **kw), _s((x1, y0), (x1, y1), **kw), _s((x1, y1), (x0, y1), **kw), _s((x0, y1), (x0, y0), **kw)]


