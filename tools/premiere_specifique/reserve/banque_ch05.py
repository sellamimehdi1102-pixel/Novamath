def _chk(cond_fn):
    return lambda: None if cond_fn() else "valeur fausse"


def _d(expr, target):
    """Dérivée de `expr` égale à `target` (SymPy)."""
    return _chk(lambda: sp.simplify(sp.diff(expr, x) - target) == 0)


def _approx(v, nd):
    return f"{round(v, nd):.{nd}f}".replace(".", "{,}")


