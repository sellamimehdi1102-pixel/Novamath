def _s(a, b, **kw):
    s = {"from": {"x": a[0], "y": a[1]}, "to": {"x": b[0], "y": b[1]}}
    s.update({k: v for k, v in kw.items() if v is not None})
    return s


def _v(a, b, label):
    return {"from": {"x": a[0], "y": a[1]}, "to": {"x": b[0], "y": b[1]}, "label": label}


