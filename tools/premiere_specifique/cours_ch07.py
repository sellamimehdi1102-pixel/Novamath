def _sq(x, y, variant, reveal=None):
    return poly([{"x": x, "y": y}, {"x": x + 1, "y": y}, {"x": x + 1, "y": y + 1}, {"x": x, "y": y + 1}],
                variant=variant, reveal=reveal)


_stair = [_sq(c, r, "a") for c in range(4) for r in range(c + 1)]
