_x = sp.symbols("x")


def _ok(cond):
    return lambda: None if cond else "valeur fausse"


def _derivee(expr, attendu):
    """Vérifie f'(x) == attendu (expressions SymPy en x)."""
    return lambda: None if sp.simplify(sp.diff(sp.sympify(expr), _x) - sp.sympify(attendu)) == 0 else "dérivée fausse"


def _cumul(n, p, k):
    return sum(comb(n, i) * p**i * (1 - p) ** (n - i) for i in range(k + 1))


def _bornes(n, p):
    """(a, b) du manuel : plus petits entiers avec P(X ⩽ a) > 0,025 et P(X ⩽ b) ⩾ 0,975."""
    a = next(k for k in range(n + 1) if _cumul(n, p, k) > F(1, 40))
    b = next(k for k in range(n + 1) if _cumul(n, p, k) >= F(39, 40))
    return a, b


def _arrondi(q, chiffres):
    return round(float(q), chiffres)


